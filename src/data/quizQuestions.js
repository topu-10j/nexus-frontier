// Helper — get a random question not yet asked
export const getRandomQuestion = (askedIds = []) => {
  const remaining = QUIZ_QUESTIONS.filter((q) => !askedIds.includes(q.id));
  if (remaining.length === 0) return QUIZ_QUESTIONS[0]; // reset
  return remaining[Math.floor(Math.random() * remaining.length)];
};